create table job_applications (
  id            uuid primary key default gen_random_uuid(),
  perusahaan    text not null,
  lokasi        text not null default '',
  jabatan       text not null,
  jenis         text not null default 'Tetap' check (jenis = any (array['MT','Magang','Tetap','Kontrak','Freelance'])),
  tempat        text not null default 'WFO' check (tempat = any (array['WFO','WFH','Hybrid'])),
  status        text not null default 'Applied' check (status = any (array['Progress','Applied','Screening','Interview','Offer','Rejected','Ghosted'])),
  tanggal_apply date not null default current_date,
  referensi     text not null default '',
  url           text not null default '',
  gaji          text not null default '',
  catatan       text not null default '',
  sumber        text not null default 'manual',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  deadline      date,
  constraint perusahaan_terisi check (length(trim(perusahaan)) > 0),
  constraint jabatan_terisi check (length(trim(jabatan)) > 0)
);
create index job_applications_status_idx on job_applications (status);
create index job_applications_tanggal_idx on job_applications (tanggal_apply desc);
create index job_applications_deadline_idx on job_applications (deadline) where deadline is not null;
-- Duplikat perusahaan+jabatan (case/whitespace-insensitive) ditolak di
-- level database, bukan cuma dicek di kode — cariDuplikat() di lib/jobs.js
-- adalah pengecekan awal yang lebih ramah pesan error, index ini jaring
-- pengamannya.
create unique index job_applications_unik on job_applications (lower(trim(perusahaan)), lower(trim(jabatan)));
